drop policy if exists "Admins can read audit logs" on public.admin_audit_logs;
create policy "Admins can read audit logs"
on public.admin_audit_logs
for select
to authenticated
using (public.is_admin());

drop policy if exists "Admins can write audit logs" on public.admin_audit_logs;
create policy "Admins can write audit logs"
on public.admin_audit_logs
for insert
to authenticated
with check (public.is_admin() and admin_id = auth.uid());

create index if not exists admin_audit_logs_admin_id_idx
  on public.admin_audit_logs(admin_id);

create index if not exists admin_audit_logs_entity_idx
  on public.admin_audit_logs(entity_type, entity_id);
